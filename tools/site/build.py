def write_if_changed(path: Path, content: str, changed: list, newline: str = "\n") -> None:
    data = content.encode("utf-8")
    if path.exists() and path.read_bytes() == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    changed.append(str(path.relative_to(ROOT)))


def build(today: dt.date, now: dt.datetime) -> list:
    raw = load_events()
    events = [Event(r, today) for r in raw if r.get("published", True)]
    upcoming, past = split_events(events)
    nxt = next_event(upcoming)
    changed = []

    index_path = ROOT / "index.html"
    text = index_path.read_text(encoding="utf-8")
    text = replace_block(text, "hero-next", hero_card(nxt))
    text = replace_block(text, "spotlight", spotlight(nxt))
    text = replace_block(text, "upcoming", event_list(
        upcoming, "", True, "        ",
        "No upcoming events yet. They are announced in the monthly newsletter, on LinkedIn and on Instagram."))
    text = replace_block(text, "past", event_list(past, "", False, "        ", "No past events yet."))
    write_if_changed(index_path, text, changed)

    for e in events:
        write_if_changed(ROOT / "events" / e.id / "index.html", event_page(e), changed)
    write_if_changed(ROOT / "events" / "index.html", events_index(upcoming, past), changed)

    # Remove generated pages of events that were deleted or unpublished.
    keep = {e.id for e in events}
    for d in sorted((ROOT / "events").iterdir()):
        page = d / "index.html"
        if d.is_dir() and d.name not in keep and page.exists() and GENERATED in page.read_text(encoding="utf-8"):
            shutil.rmtree(d)
            changed.append("events/%s/ (removed)" % d.name)

    before = dump_events(raw)
    versions = ics_versions(events, {r["id"]: r for r in raw}, now)
    for e in events:
        if e.id in versions:
            seq, stamp = versions[e.id]
            write_if_changed(ROOT / "cal" / ("%s.ics" % e.id), ics_file(e, seq, stamp), changed)
    if dump_events(raw) != before:
        write_if_changed(EVENTS_JSON, dump_events(raw), changed)
    return changed


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="validate events/events.json and exit")
    ap.add_argument("--today", help="YYYY-MM-DD; decides upcoming vs past (default: today in Amsterdam)")
    args = ap.parse_args(argv)
    try:
        if args.check:
            n = len(load_events())
            print("events.json OK (%d events)" % n)
            return 0
        now = dt.datetime.now(TZ).replace(microsecond=0)
        today = dt.date.fromisoformat(args.today) if args.today else now.date()
        changed = build(today, now)
    except ValidationError as exc:
        print("ERROR: %s" % exc, file=sys.stderr)
        return 1
    if changed:
        print("Updated %d file(s):\n  %s" % (len(changed), "\n  ".join(changed)))
    else:
        print("Nothing to update: generated files are current.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
