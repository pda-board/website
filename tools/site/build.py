def replace_block(text: str, name: str, content: str) -> str:
    pat = re.compile(r"(<!-- BUILD:%s START[^>]*-->\n)(.*?)(^[ \t]*<!-- BUILD:%s END -->)" % (name, name), re.S | re.M)
    if not pat.search(text):
        raise ValidationError("index.html: markers <!-- BUILD:%s START --> / <!-- BUILD:%s END --> not found" % (name, name))
    return pat.sub(lambda m: m.group(1) + content + "\n" + m.group(3), text, count=1)


