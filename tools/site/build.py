#!/usr/bin/env python3
"""Build the event parts of the TU/e PDA website from events/events.json.

    python3 tools/site/build.py              # build (today's date decides upcoming/past)
    python3 tools/site/build.py --check      # validate the JSON only
    python3 tools/site/build.py --today 2026-12-01   # pretend it is another day

What it writes (all committed, the site is served as-is with no build step):
  * index.html, only between the <!-- BUILD:name START --> / <!-- BUILD:name END -->
    markers (hero "Next up" card, #next-event spotlight, upcoming and past lists);
  * events/<id>/index.html, one page per published event;
  * events/index.html, the list of all events;
  * cal/<id>.ics for every dated event. SEQUENCE is the "sequence" field in
    events.json; the build bumps it (and rewrites events.json) only when the
    calendar content differs from the .ics already on disk.

Python 3.9+ standard library only. Output is deterministic for a given date.
"""
