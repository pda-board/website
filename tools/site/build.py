# ---------------------------------------------------------------- validation

def parse_local(value: str) -> dt.datetime:
    return dt.datetime.strptime(value, "%Y-%m-%dT%H:%M").replace(tzinfo=TZ)


def parse_label(label: str):
    """'TBA Dec 2026' / 'Dec 2021' / '15 Jun 2026' / '2027' -> (first_day, last_day, big, small)."""
    m = LABEL_RE.match(label.strip())
    if not m:
        return None
    year = int(m.group("year"))
    mon_txt = m.group("mon")
    month = None
    if mon_txt:
        key = mon_txt[:3].title()
        if key not in MONTHS:
            return None
        month = MONTHS.index(key) + 1
    day = int(m.group("day")) if m.group("day") else None
    if day and not month:
        return None
    try:
        if day:
            first = last = dt.date(year, month, day)
        elif month:
            first = dt.date(year, month, 1)
            last = (dt.date(year + (month == 12), month % 12 + 1, 1) - dt.timedelta(days=1))
        else:
            first, last = dt.date(year, 1, 1), dt.date(year, 12, 31)
    except ValueError:
        return None
    if m.group("tba"):
        big, small = "TBA", label.strip()[3:].strip()
    elif day:
        big, small = str(day), "%s %d" % (MONTHS[month - 1], year)
    elif month:
        big, small = MONTHS[month - 1], str(year)
    else:
        big, small = str(year), ""
    return first, last, big, small


def safe_url(value) -> bool:
    """A link the site may print: a relative path or #anchor, or an absolute
    http(s)/mailto URL. No whitespace or control characters anywhere (browsers
    strip them, which is how ' javascript:' or 'java\tscript:' sneak through)."""
    if not isinstance(value, str) or value == "" or re.search(r"[\x00-\x20\x7f]", value):
        return False
    if re.match(r"(?i)^(https?://|mailto:)", value):
        return True
    return not re.match(r"^[^/?#]*:", value) and not value.startswith("//")


def is_rel_or_url(value) -> bool:
    return safe_url(value)


def validate(events) -> list:
    """Return a list of human-readable error strings (empty when valid)."""
    errors = []
    if not isinstance(events, list):
        return ["events.json must contain a JSON list of event objects"]
    seen = set()
    for i, ev in enumerate(events):
        where = "event #%d" % (i + 1)
        if not isinstance(ev, dict):
            errors.append("%s: must be a JSON object" % where)
            continue
        if isinstance(ev.get("id"), str):
            where = "event #%d (%s)" % (i + 1, ev["id"])
        for key in REQUIRED:
            if not isinstance(ev.get(key), str) or not ev.get(key).strip():
                errors.append("%s: '%s' is required and must be a non-empty string" % (where, key))
        unknown = sorted(set(ev) - set(FIELDS))
        if unknown:
            errors.append("%s: unknown field(s) %s" % (where, ", ".join(unknown)))
        eid = ev.get("id")
        if isinstance(eid, str):
            if not ID_RE.match(eid):
                errors.append("%s: 'id' must be a lowercase slug like 'borrel-glow-walk-2026'" % where)
            if eid in seen:
                errors.append("%s: duplicate id '%s'" % (where, eid))
            seen.add(eid)
        if ev.get("type") not in TYPES and isinstance(ev.get("type"), str):
            errors.append("%s: 'type' must be one of %s" % (where, ", ".join(TYPES)))
        for key in ("start", "end"):
            v = ev.get(key)
            if v is None:
                continue
            if not isinstance(v, str) or not DT_RE.match(v):
                errors.append("%s: '%s' must be null or local time like 2026-11-10T17:30 (got %r)" % (where, key, v))
                continue
            try:
                parse_local(v)
            except ValueError:
                errors.append("%s: '%s' is not a valid date/time (%s)" % (where, key, v))
        start, end = ev.get("start"), ev.get("end")
        if end and not start:
            errors.append("%s: 'end' is set but 'start' is null" % where)
        if (isinstance(start, str) and isinstance(end, str) and DT_RE.match(start) and DT_RE.match(end)
                and end < start):
            errors.append("%s: 'end' (%s) is before 'start' (%s)" % (where, end, start))
        label = ev.get("date_label")
        if label is not None and not isinstance(label, str):
            errors.append("%s: 'date_label' must be a string or null" % where)
        elif not start:
            if not label:
                errors.append("%s: needs either 'start' or 'date_label' (e.g. 'TBA Dec 2026')" % where)
            elif not parse_label(label):
                errors.append("%s: 'date_label' %r must look like 'TBA Dec 2026', 'Dec 2021', '15 Jun 2026' or '2027'"
                              % (where, label))
        for key in ("time_label", "location_url", "registration_url", "price", "image", "flyer_pdf",
                    "external_url", "description", "location"):
            v = ev.get(key)
            if v is not None and not isinstance(v, str):
                errors.append("%s: '%s' must be a string or null" % (where, key))
        for key in ("location_url", "registration_url", "external_url"):
            v = ev.get(key)
            if isinstance(v, str) and v and not (safe_url(v) and re.match(r"(?i)^(https?://|mailto:)", v)):
                errors.append("%s: '%s' must be an absolute http(s) or mailto link" % (where, key))
        for key in ("image", "flyer_pdf"):
            v = ev.get(key)
            if isinstance(v, str) and v:
                if SCHEME_RE.match(v):
                    if not v.startswith("https://"):
                        errors.append("%s: '%s' must be a relative path or an https URL" % (where, key))
                elif v.startswith("/") or ".." in v.split("/"):
                    errors.append("%s: '%s' must be relative to the site root, like img/flyers/x.jpg" % (where, key))
                elif not (ROOT / v).is_file():
                    errors.append("%s: '%s' file not found: %s" % (where, key, v))
        for key in ("registration_required", "featured", "published"):
            if key in ev and not isinstance(ev[key], bool):
                errors.append("%s: '%s' must be true or false" % (where, key))
        tags = ev.get("tags", [])
        if not isinstance(tags, list) or not all(isinstance(t, str) and t.strip() for t in tags):
            errors.append("%s: 'tags' must be a list of strings" % where)
        prog = ev.get("programme", [])
        if prog is None:
            prog = []
        if not isinstance(prog, list) or not all(
                isinstance(p, dict) and isinstance(p.get("time"), str) and isinstance(p.get("item"), str)
                and set(p) <= {"time", "item"} for p in prog):
            errors.append("%s: 'programme' must be a list of {\"time\": str, \"item\": str}" % where)
        sq = ev.get("sequence", 0)
        if not isinstance(sq, int) or isinstance(sq, bool) or sq < 0:
            errors.append("%s: 'sequence' must be a non-negative integer (calendar SEQUENCE)" % where)
        cta = ev.get("past_cta")
        if cta is not None and not (isinstance(cta, dict) and isinstance(cta.get("label"), str) and cta["label"].strip() != ""
                                    and is_rel_or_url(cta.get("href")) and set(cta) <= {"label", "href"}):
            errors.append("%s: 'past_cta' must be null or {\"label\": str, \"href\": str}" % where)
    return errors


def load_events(path: Path = EVENTS_JSON):
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ValidationError("%s is not valid JSON: %s" % (path, exc))
    errors = validate(data)
    if errors:
        raise ValidationError("%s has %d problem(s):\n  - %s" % (path.name, len(errors), "\n  - ".join(errors)))
    return data


# ---------------------------------------------------------------- model

class Event:
    def __init__(self, raw: dict, today: dt.date):
        d = dict(DEFAULTS)
        d.update({k: v for k, v in raw.items()})
        if d["programme"] is None:
            d["programme"] = []
        self.d = d
        self.id = d["id"]
        self.start = parse_local(d["start"]) if d["start"] else None
        self.end = parse_local(d["end"]) if d["end"] else None
        if self.start:
            last = (self.end or self.start).date()
            self.sort_key = self.start.replace(tzinfo=None)
            self.big, self.small = str(self.start.day), "%s %d" % (MONTHS[self.start.month - 1], self.start.year)
        else:
            first, last, self.big, self.small = parse_label(d["date_label"])
            self.sort_key = dt.datetime.combine(last, dt.time(23, 59))
        self.upcoming = last >= today

    def __getitem__(self, key):
        return self.d[key]

    @property
    def dated(self) -> bool:
        return self.start is not None

    @property
    def url(self) -> str:
        return SITE + "events/%s/" % self.id

    @property
    def cal_end(self) -> dt.datetime:
        """End for calendar entries: the given end, or two hours after start."""
        return self.end or self.start + dt.timedelta(hours=2)

    def time_text(self) -> str:
        if self.d["time_label"]:
            return self.d["time_label"]
        if not self.start:
            return ""
        if self.end and self.end.date() == self.start.date():
            return "%s – %s" % (self.start.strftime("%H:%M"), self.end.strftime("%H:%M"))
        if self.end:
            return "%s – %s %s" % (self.start.strftime("%H:%M"), short_date(self.end), self.end.strftime("%H:%M"))
        return self.start.strftime("%H:%M")

    def date_text(self, long=False) -> str:
        if self.start:
            return long_date(self.start) if long else short_date(self.start)
        return self.d["date_label"]

    def when_text(self) -> str:
        t = self.time_text()
        return "%s, %s" % (self.date_text(), t) if t else self.date_text()


def short_date(d) -> str:
    return "%s %d %s %d" % (DAYS[d.weekday()], d.day, MONTHS[d.month - 1], d.year)


def long_date(d) -> str:
    return "%s %d %s %d" % (DAYS_LONG[d.weekday()], d.day, MONTHS_LONG[d.month - 1], d.year)


def split_events(events):
    upcoming = sorted((e for e in events if e.upcoming), key=lambda e: (e.sort_key, e.id))
    past = sorted((e for e in events if not e.upcoming), key=lambda e: e.id)
    past = sorted(past, key=lambda e: e.sort_key, reverse=True)
    return upcoming, past


def next_event(upcoming):
    dated = [e for e in upcoming if e.dated]
    for e in dated:
        if e["featured"]:
            return e
    return dated[0] if dated else None


# ---------------------------------------------------------------- html helpers

def esc(s) -> str:
    return html.escape(str(s), quote=True)


def q(s) -> str:
    return quote(s, safe="")


def href(prefix: str, url: str) -> str:
    """Site-relative paths get the page's prefix; absolute URLs and mailto: stay."""
    if SCHEME_RE.match(url) or url.startswith("//"):
        return url
    return prefix + url


def host_label(url: str) -> str:
    host = urlparse(url).hostname or url
    return host[4:] if host.startswith("www.") else host


def markdown(text: str, prefix: str) -> str:
    """Paragraphs separated by blank lines, [text](url) links, nothing else."""
    out = []
    for para in re.split(r"\n\s*\n", (text or "").strip()):
        if not para.strip():
            continue
        parts, pos = [], 0
        for m in LINK_RE.finditer(para):
            parts.append(esc(para[pos:m.start()]))
            label, url = m.group(1), m.group(2)
            if not safe_url(url):
                parts.append(esc(label))
            else:
                parts.append('<a href="%s">%s</a>' % (esc(href(prefix, url)), esc(label)))
            pos = m.end()
        parts.append(esc(para[pos:]))
        out.append("<p>%s</p>" % "".join(parts).strip().replace("\n", "<br>\n"))
    return "\n".join(out)


def image_size(path: Path):
    """(width, height) of a PNG or JPEG, or None."""
    try:
        data = path.read_bytes()
    except OSError:
        return None
    if data[:8] == b"\x89PNG\r\n\x1a\n":
        return struct.unpack(">II", data[16:24])
    if data[:2] == b"\xff\xd8":
        i = 2
        while i + 9 < len(data):
            if data[i] != 0xFF:
                i += 1
                continue
            marker = data[i + 1]
            if marker in (0xC0, 0xC1, 0xC2, 0xC3, 0xC5, 0xC6, 0xC7, 0xC9, 0xCA, 0xCB, 0xCD, 0xCE, 0xCF):
                h, w = struct.unpack(">HH", data[i + 5:i + 9])
                return w, h
            if marker in (0xD8, 0x01) or 0xD0 <= marker <= 0xD7:
                i += 2
                continue
            i += 2 + struct.unpack(">H", data[i + 2:i + 4])[0]
    return None


