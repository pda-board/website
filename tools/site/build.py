# ---------------------------------------------------------------- share / calendar links

def iso_offset(d: dt.datetime) -> str:
    s = d.strftime("%Y-%m-%dT%H:%M:%S%z")
    return s[:-2] + ":" + s[-2:]


def utc_stamp(d: dt.datetime) -> str:
    return d.astimezone(UTC).strftime("%Y%m%dT%H%M%SZ")


def email_body(e: Event, newline: str = "\n") -> str:
    lines = ["Hi,", "", "You might like this event of the TU/e Postdoc Association:", "", e["title"],
             "When: " + e.when_text()]
    if e["location"]:
        lines.append("Where: " + e["location"])
    if e["price"]:
        lines.append("Price: " + e["price"])
    lines += ["", e["summary"], ""]
    if e["registration_url"] and e.upcoming:
        lines.append(("Registration is mandatory: " if e["registration_required"] else "Register: ")
                     + e["registration_url"])
    lines.append("Details: " + e.url)
    return newline.join(lines)


def calendar_body(e: Event) -> str:
    body = e["summary"]
    if e["registration_url"]:
        body += "\n\nRegister: " + e["registration_url"]
    return body + "\n\nDetails: " + e.url


def calendar_location(e: Event) -> str:
    """Location for calendar entries; adds the city so map lookups find the campus."""
    loc = e["location"] or ""
    if loc and "eindhoven" not in loc.lower():
        loc += ", Eindhoven"
    return loc


def share_links(e: Event, prefix: str) -> dict:
    subject = "%s (%s)" % (e["title"], e.date_text())
    links = {
        "outlook": "https://outlook.office.com/mail/deeplink/compose?subject=%s&body=%s"
                   % (q(subject), q(email_body(e))),
        "mailto": "mailto:?subject=%s&body=%s" % (q(subject), q(email_body(e, "\r\n"))),
        "whatsapp": "https://wa.me/?text=%s" % q("%s, %s\n%s" % (e["title"], e.when_text(), e.url)),
        "linkedin": "https://www.linkedin.com/sharing/share-offsite/?url=%s" % q(e.url),
        "page": prefix + "events/%s/" % e.id,
        "image": href(prefix, e["image"]) if e["image"] else None,
    }
    if e.dated:
        links["ics"] = prefix + "cal/%s.ics" % e.id
        links["outlook_cal"] = (
            "https://outlook.office.com/calendar/0/deeplink/compose?path=%%2Fcalendar%%2Faction%%2Fcompose"
            "&rru=addevent&subject=%s&startdt=%s&enddt=%s&location=%s&body=%s"
            % (q(e["title"]), q(iso_offset(e.start)), q(iso_offset(e.cal_end)), q(calendar_location(e)),
               q(calendar_body(e))))
        links["google"] = (
            "https://calendar.google.com/calendar/render?action=TEMPLATE&text=%s&dates=%s/%s&details=%s&location=%s"
            % (q(e["title"]), utc_stamp(e.start), utc_stamp(e.cal_end), q(calendar_body(e)), q(calendar_location(e))))
    return links


def share_attrs(e: Event) -> str:
    return ' data-share-url="%s" data-share-title="%s" data-share-text="%s"' % (
        esc(e.url), esc(e["title"]), esc("%s, %s" % (e["title"], e.when_text())))


def share_entries(e: Event, prefix: str):
    """(kind, href, icon, label, sublabel, extra-attrs) for every share option."""
    L = share_links(e, prefix)
    ext = ' target="_blank" rel="noopener"'
    items = [
        ("a", L["outlook"], "mail", "Email via Outlook", "TU/e Microsoft 365", ext),
        ("a", L["mailto"], "send", "Other email app", "", ""),
        ("a", L["whatsapp"], "chat", "WhatsApp", "", ext),
        ("a", L["linkedin"], "linkedin", "LinkedIn", "", ext),
        ("button", None, "phone", "More apps", "Instagram, Teams, …", " data-native-share hidden"),
        ("a", L["page"], "link", "Copy link", "", " data-copy"),
    ]
    if L["image"]:
        items.append(("a", L["image"], "download", "Download image", "For a story or post",
                      ' download="%s"' % esc(os.path.basename(e["image"]))))
    return items


def calendar_entries(e: Event, prefix: str):
    L = share_links(e, prefix)
    ext = ' target="_blank" rel="noopener"'
    return [
        ("a", L["outlook_cal"], "calendar", "Add to Outlook calendar", "", ext),
        ("a", L["ics"], "download", "Other calendar apps", ".ics file", " download"),
        ("a", L["google"], "calendar", "Google Calendar", "", ext),
    ]


def menu_item(entry) -> str:
    kind, url, ic, label, sub, extra = entry
    lab = '<span class="label">%s</span>' % esc(label) if "data-copy" in extra else esc(label)
    inner = "%s<span>%s%s</span>" % (icon(ic), lab, "<small>%s</small>" % esc(sub) if sub else "")
    if kind == "button":
        return '<button type="button" class="share-item"%s>%s</button>' % (extra, inner)
    return '<a class="share-item" href="%s"%s>%s</a>' % (esc(url), extra, inner)


def share_menu(e: Event, prefix: str, align_left: bool = False) -> str:
    items = [menu_item(x) for x in share_entries(e, prefix)]
    if e.dated and e.upcoming:
        cal = calendar_entries(e, prefix)
        items += ['<hr class="share-sep">', menu_item(cal[0]), menu_item(cal[1])]
    return ('<details class="share"%s>'
            '<summary class="btn btn-ghost share-toggle" aria-label="Share: %s">%sShare</summary>'
            '<div class="share-menu%s">%s<span class="share-live visually-hidden" aria-live="polite"></span></div>'
            '</details>') % (share_attrs(e), esc(e["title"]), icon("share", 16),
                             " align-left" if align_left else "", "".join(items))


