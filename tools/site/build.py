# ---------------------------------------------------------------- ics

def ics_escape(s: str) -> str:
    s = s.replace("\r\n", "\n").replace("\r", "\n")  # a bare CR must not start a new ICS line
    return s.replace("\\", "\\\\").replace(";", "\\;").replace(",", "\\,").replace("\n", "\\n")


def fold(line: str) -> str:
    """RFC 5545 3.1: lines of at most 75 octets, continuation lines start with one space."""
    out, cur, size, limit = [], "", 0, 75
    for ch in line:
        n = len(ch.encode("utf-8"))
        if size + n > limit:
            out.append(cur)
            cur, size, limit = " ", 1, 75
        cur += ch
        size += n
    out.append(cur)
    return "\r\n".join(out)


def unfold(text: str):
    return re.sub(r"\r?\n[ \t]", "", text).splitlines()


def vevent_lines(e: Event):
    lines = ["DTSTART:" + utc_stamp(e.start), "DTEND:" + utc_stamp(e.cal_end),
             "SUMMARY:" + ics_escape(e["title"])]
    if e["location"]:
        lines.append("LOCATION:" + ics_escape(calendar_location(e)))
    lines.append("DESCRIPTION:" + ics_escape(calendar_body(e)))
    lines.append("URL:" + e.url)
    return lines


def ics_file(e: Event, sequence: int, dtstamp: str) -> str:
    lines = ["BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//TU/e Postdoc Association//Website//EN",
             "CALSCALE:GREGORIAN", "METHOD:PUBLISH", "BEGIN:VEVENT",
             "UID:%s@%s" % (e.id, UID_DOMAIN), "SEQUENCE:%d" % sequence, "DTSTAMP:" + dtstamp]
    lines += vevent_lines(e)
    lines += ["END:VEVENT", "END:VCALENDAR"]
    return "\r\n".join(fold(l) for l in lines) + "\r\n"


ICS_PROPS = ("DTSTART", "DTEND", "SUMMARY", "LOCATION", "DESCRIPTION", "URL")


def ics_versions(events, raw_by_id: dict, now: dt.datetime) -> dict:
    """Return {id: (sequence, dtstamp)}.

    The SEQUENCE lives in events.json ("sequence", also read by tools/mail). It is
    bumped (in `raw_by_id`, which the caller writes back) only when the calendar
    content differs from the .ics file already on disk; DTSTAMP is kept from that
    file unless the content changed, so rebuilding is a no-op.
    """
    stamp_now = now.astimezone(UTC).strftime("%Y%m%dT%H%M%SZ")
    result = {}
    for e in events:
        if not e.dated:
            continue
        seq, stamp = int(raw_by_id[e.id].get("sequence", 0)), stamp_now
        path = ROOT / "cal" / ("%s.ics" % e.id)
        if path.exists():
            old = unfold(path.read_text(encoding="utf-8"))
            props = [l for l in old if l.split(":", 1)[0] in ICS_PROPS]
            seqs = [int(l.split(":", 1)[1]) for l in old if l.startswith("SEQUENCE:")]
            stamps = [l.split(":", 1)[1] for l in old if l.startswith("DTSTAMP:")]
            seq = max([seq] + seqs)
            if props != vevent_lines(e):
                seq += 1
            elif stamps:
                stamp = stamps[0]
        if raw_by_id[e.id].get("sequence") != seq:
            raw_by_id[e.id]["sequence"] = seq
        result[e.id] = (seq, stamp)
    return result


